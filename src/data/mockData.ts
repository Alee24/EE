// Helper generator for seat layout
export function generateSeatsForBus(totalSeats: number = 48, baseFare: number = 1800): Seat[] {
  const seats: Seat[] = [];
  const rows = Math.ceil(totalSeats / 4);
  const colLetters = ['A', 'B', 'C', 'D'];

  let count = 0;
  for (let r = 1; r <= rows; r++) {
    for (let c = 0; c < 4; c++) {
      count++;
      if (count > totalSeats) break;
      const seatNum = `${r}${colLetters[c]}`;
      // VIP front rows (1-2) slightly higher fare
      const isVip = r <= 2;
      const price = isVip ? baseFare + 200 : baseFare;
      
      // Random pre-booked seats for realism
      const isBooked = [2, 5, 8, 12, 18, 19, 24, 25, 30, 31, 36, 42].includes(count);

      seats.push({
        id: `seat_${seatNum}`,
        number: seatNum,
        row: r,
        column: c + 1,
        class: isVip ? 'vip' : 'executive',
        priceKsh: price,
        isBooked,
        isWindow: c === 0 || c === 3,
        isAisle: c === 1 || c === 2,
        bookedByPassengerName: isBooked ? 'Booked Passenger' : undefined,
      });
    }
  }
  return seats;
}

